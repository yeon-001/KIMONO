# 내림차순 가로 막대그래프 생성 함수
def draw_sorted_bar_chart(sub_df, bar_color):
    chart = (
        alt.Chart(sub_df)
        .mark_bar(color=bar_color)
        .encode(
            x=alt.X("득표수:Q", title="득표수 (표)"),
            y=alt.Y(
                "항목:N", sort="-x", title=None
            ),  # sort='-x'로 득표수 기준 내림차순 정렬
            tooltip=["순위", "항목", "득표수"],
        )
        .properties(height=max(350, len(sub_df) * 24))
    )
    return chart


