df = pd.DataFrame(data)


def draw_sorted_bar_chart(sub_df, bar_color):
    max_val = sub_df["득표수"].max()

    base = alt.Chart(sub_df).encode(
        x=alt.X(
            "득표수:Q",
            title="득표수 (표)",
            scale=alt.Scale(domain=[0, max_val * 1.15]),  # 숫자 공간 확보
        ),
        y=alt.Y("항목:N", sort="-x", title=None),
        tooltip=["순위", "항목", "득표수"],
    )

    bars = base.mark_bar(color=bar_color)

    # 막대 끝에 숫자 표시
    text = base.mark_text(
        align="left",
        baseline="middle",
        dx=5,  # 막대 끝에서 오른쪽으로 5px 여백
    ).encode(text="득표수:Q")

    return (bars + text).properties(height=max(350, len(sub_df) * 24))


